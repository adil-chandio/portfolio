#!/usr/bin/env python3
"""Rewrite the VOICE_CLIPS:auto block in assets/assistant.js to match the
clips actually present in assets/voice/*.mp3. Keeps the browser's clip list
truthful forever — never lists a file that isn't there."""
import glob, os, re, sys

voice_dir = sys.argv[1] if len(sys.argv) > 1 else 'assets/voice'
assistant = sys.argv[2] if len(sys.argv) > 2 else 'assets/assistant.js'
keys = sorted(os.path.basename(f)[:-4] for f in glob.glob(os.path.join(voice_dir, '*.mp3')))
replacement = ("/* VOICE_CLIPS:auto — regenerated by tools/gen_voice.py */\n"
               "const VOICE_CLIPS = new Set('%s'.split(','));\n"
               "/* VOICE_CLIPS:end */") % ','.join(keys)
src = open(assistant, encoding='utf-8').read()
out, n = re.subn(r"/\* VOICE_CLIPS:auto[^\n]*\*/\nconst VOICE_CLIPS = new Set\('[^']*'\.split\(','\)\);\n/\* VOICE_CLIPS:end \*/", replacement, src)
if n != 1:
    print(f"ERROR: expected exactly 1 VOICE_CLIPS block, found {n}", file=sys.stderr)
    sys.exit(1)
open(assistant, 'w', encoding='utf-8').write(out)
print(f"VOICE_CLIPS synced: {len(keys)} clips")
